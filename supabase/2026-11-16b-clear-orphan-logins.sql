-- ============================================================================
-- 2026-11-16 — ปลดรหัสพนักงานที่ติด "User already registered" ทันที
--
-- ใช้ได้เลยโดยไม่ต้องรอปล่อยเว็บเวอร์ชันใหม่: ลบบัญชีเข้าสู่ระบบที่ค้างจากการ
-- เพิ่มพนักงานไม่สำเร็จ แล้วกลับไปเพิ่มพนักงานรหัสนั้นที่หน้าเว็บได้ตามปกติ
--
-- ลบเฉพาะบัญชีที่ครบทุกข้อ:
--   - เป็นบัญชีพนักงาน (อีเมล ...@globe.local)
--   - ไม่มีข้อมูลพนักงาน (ไม่อยู่ในรายชื่อพนักงาน)
--   - ไม่มีเอกสารสักฉบับ
--   - สร้างไว้เกิน 10 นาทีแล้ว (ไม่ไปชนกับการเพิ่มพนักงานที่กำลังทำอยู่)
-- พนักงานที่อยู่ในรายชื่อไม่ถูกแตะเลย
--
-- Run in Supabase → SQL Editor. ผลลัพธ์คือรายชื่อบัญชีที่ลบไป (ว่าง = ไม่มีค้าง)
-- ============================================================================

delete from auth.users u
 where lower(u.email) like '%@globe.local'
   and u.created_at < now() - interval '10 minutes'
   and not exists (select 1 from profiles p where p.uid = u.id)
   and not exists (select 1 from submissions s where s."createdBy" = u.id)
returning u.email as "ลบบัญชีค้างแล้ว", u.created_at as "สร้างเมื่อ";
